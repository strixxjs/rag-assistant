#!/usr/bin/env python3
"""
eval/gen_dataset_stage3.py — Stage 3: Regenerate eval/dataset.json against rag_eval.

Split:
  - 20 questions generated by Groq (qwen/qwen3.8-27b)
      - 15 single-chunk
      - 5 multi-chunk (answer spans 2 chunks from the same repo)
  - 10 hand-written slots (question = "[HAND-WRITTEN]", answer = "")

Question quality rules (enforced in prompts):
  - Problem-framing, NOT lookup: "why does X fail when…" not "what does doc say about X"
  - NO words from the document title or headings
  - ground_truth_answer: ≤ 2 sentences of factual content, NOT the chunk text verbatim
"""

import json
import logging
import os
import random
import sys
import time
import uuid
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger(__name__)

QDRANT_URL    = os.getenv("QDRANT_URL", "http://localhost:6333")
COLLECTION    = "rag_eval"
DATASET_PATH  = Path("eval/dataset.json")
GROQ_API_KEY  = os.getenv("GROQ_API_KEY", "")
GROQ_MODEL    = "qwen/qwen3.8-27b"
GROQ_ENDPOINT = "https://api.groq.com/openai/v1/chat/completions"
SEED          = 42


# ---------------------------------------------------------------------------
# Groq helper
# ---------------------------------------------------------------------------

def groq_call(prompt: str, max_tokens: int = 500, retries: int = 2) -> str | None:
    import httpx
    headers = {
        "Authorization": f"Bearer {GROQ_API_KEY}",
        "Content-Type": "application/json",
    }
    body = {
        "model": GROQ_MODEL,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens,
        "temperature": 0.5,
    }
    for attempt in range(retries + 1):
        try:
            r = httpx.post(GROQ_ENDPOINT, headers=headers, json=body, timeout=40)
            if r.status_code == 429:
                wait = 30 * (attempt + 1)
                log.warning(f"Rate-limited (429), sleeping {wait}s …")
                time.sleep(wait)
                continue
            r.raise_for_status()
            return r.json()["choices"][0]["message"]["content"].strip()
        except Exception as exc:
            log.warning(f"Groq error (attempt {attempt+1}): {exc}")
            if attempt < retries:
                time.sleep(5)
    return None


def parse_qa(raw: str) -> dict | None:
    if not raw or "QUESTION:" not in raw or "ANSWER:" not in raw:
        return None
    try:
        q = raw.split("QUESTION:")[1].split("ANSWER:")[0].strip().strip('"*`')
        a = raw.split("ANSWER:")[1].strip().strip('"*`')
        if len(q) < 15 or len(a) < 10:
            return None
        return {"question": q, "answer": a}
    except Exception:
        return None


# ---------------------------------------------------------------------------
# Prompt templates
# ---------------------------------------------------------------------------

SINGLE_PROMPT = """\
You are writing questions for a developer Q&A benchmark testing a search/RAG system.
A developer is frustrated, hitting an issue/error, and searching for help. Write ONE question
they might type into search or ask a colleague — describing a SYMPTOM they observe or a GOAL
they cannot achieve, in their own words.

Rules:
- Describe a practical SYMPTOM or GOAL (e.g. "My endpoint opens a new database connection on every request instead of reusing one — how do I share it?", "My template loop is firing hundreds of queries, one per row. How do I fetch the related objects in a single query?").
- NEVER write a generic doc lookup (NO "What does X do", "How does Y work").
- Do NOT reuse words from the document title, headings, or any exact API/function/class names that appear in the chunk.
- The answer must be found in the chunk below, but the question must be phrased using the developer's problem framing.
- Write a SHORT FACTUAL ANSWER (1-2 sentences). Do NOT copy chunk text verbatim.

Chunk (repo: {repo}, file: {source_file}):
\"\"\"
{text}
\"\"\"

Format (strictly follow this):
QUESTION: <your question describing symptom or goal>
ANSWER: <short factual answer in 1-2 sentences>"""

MULTI_PROMPT = """\
You are writing questions for a developer Q&A benchmark testing a search/RAG system.
Write ONE question describing a complex problem, symptom, or goal that REQUIRES synthesizing
information from BOTH excerpts below to be answered correctly.

Rules:
- Describe a practical SYMPTOM or GOAL in a real developer workflow.
- Do NOT reuse words from document titles, headings, or exact API/function/class names that appear in the chunks.
- The correct answer MUST require information from BOTH excerpts.
- Write a SHORT FACTUAL ANSWER (2-3 sentences) synthesizing both excerpts. Do NOT copy chunk text verbatim.

Excerpt 1 (repo: {repo}, file: {source_file1}):
\"\"\"
{text1}
\"\"\"

Excerpt 2 (same repo, file: {source_file2}):
\"\"\"
{text2}
\"\"\"

Format (strictly follow this):
QUESTION: <your question synthesizing both excerpts>
ANSWER: <short factual answer in 2-3 sentences>"""


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    if not GROQ_API_KEY:
        log.error("GROQ_API_KEY not set.")
        sys.exit(1)

    from qdrant_client import QdrantClient
    from qdrant_client.models import ScrollRequest

    client = QdrantClient(
        url=QDRANT_URL,
        prefer_grpc=False,
        check_compatibility=False,
        timeout=30,
    )

    # Verify collection exists
    info = client.get_collection(COLLECTION)
    log.info(f"Collection '{COLLECTION}': {info.points_count} chunks.")

    # ------------------------------------------------------------------
    # Sample chunks
    # ------------------------------------------------------------------
    rng = random.Random(SEED)

    # Scroll a large random sample for selection
    log.info("Sampling chunks from Qdrant …")
    chunks = []
    offset = None
    while len(chunks) < 5_000:
        batch, offset = client.scroll(
            collection_name=COLLECTION,
            limit=200,
            offset=offset,
            with_payload=True,
            with_vectors=False,
        )
        chunks.extend(batch)
        if offset is None:
            break

    log.info(f"Sampled {len(chunks)} chunks.")

    # Group by repo for multi-chunk pairing
    by_repo: dict[str, list] = {}
    for c in chunks:
        repo = c.payload.get("repo", "unknown")
        by_repo.setdefault(repo, []).append(c)

    rng.shuffle(chunks)

    entries: list[dict] = []

    # ------------------------------------------------------------------
    # 15 single-chunk questions
    # ------------------------------------------------------------------
    log.info("Generating 15 single-chunk questions …")
    pool = [c for c in chunks if len(c.payload.get("text", "")) > 200]
    rng.shuffle(pool)
    single_pool = pool[:60]  # work through up to 60 to get 15 successes

    single_done = 0
    for chunk in single_pool:
        if single_done >= 15:
            break
        text = chunk.payload.get("text", "")
        repo = chunk.payload.get("repo", "")
        source_file = chunk.payload.get("source_file", "")
        raw = groq_call(SINGLE_PROMPT.format(repo=repo, source_file=source_file, text=text[:800]))
        qa = parse_qa(raw)
        if not qa:
            log.warning(f"  skipped chunk {chunk.id} (bad parse)")
            time.sleep(1.5)
            continue
        entries.append({
            "id":                      str(uuid.uuid4()),
            "question":                qa["question"],
            "ground_truth_chunk_id":   str(chunk.id),
            "ground_truth_answer":     qa["answer"],
        })
        single_done += 1
        log.info(f"  [{single_done}/15] Q: {qa['question'][:80]} …")
        time.sleep(2.0)  # rate-limit headroom

    log.info(f"Single-chunk: {single_done}/15 generated.")

    # ------------------------------------------------------------------
    # 5 multi-chunk questions
    # ------------------------------------------------------------------
    log.info("Generating 5 multi-chunk questions …")
    multi_done = 0
    for repo, repo_chunks in by_repo.items():
        if multi_done >= 5:
            break
        long_chunks = [c for c in repo_chunks if len(c.payload.get("text", "")) > 200]
        if len(long_chunks) < 2:
            continue
        rng.shuffle(long_chunks)
        c1, c2 = long_chunks[0], long_chunks[1]
        raw = groq_call(
            MULTI_PROMPT.format(
                repo=repo,
                source_file1=c1.payload.get("source_file", ""),
                source_file2=c2.payload.get("source_file", ""),
                text1=c1.payload.get("text", "")[:600],
                text2=c2.payload.get("text", "")[:600],
            ),
            max_tokens=600,
        )
        qa = parse_qa(raw)
        if not qa:
            log.warning(f"  skipped multi pair for {repo}")
            time.sleep(1.5)
            continue
        entries.append({
            "id":                      str(uuid.uuid4()),
            "question":                qa["question"],
            "ground_truth_chunk_id":   [str(c1.id), str(c2.id)],
            "ground_truth_answer":     qa["answer"],
        })
        multi_done += 1
        log.info(f"  [{multi_done}/5] Q: {qa['question'][:80]} …")
        time.sleep(2.0)

    log.info(f"Multi-chunk: {multi_done}/5 generated.")

    # Fill remaining multi-chunk slots with fallback if needed
    while multi_done < 5:
        pool2 = [c for c in chunks if len(c.payload.get("text", "")) > 200]
        rng.shuffle(pool2)
        c1, c2 = pool2[0], pool2[1]
        entries.append({
            "id":                      str(uuid.uuid4()),
            "question":                "[HAND-WRITTEN]",
            "ground_truth_chunk_id":   [str(c1.id), str(c2.id)],
            "ground_truth_answer":     "",
        })
        multi_done += 1

    # ------------------------------------------------------------------
    # 10 hand-written slots
    # ------------------------------------------------------------------
    log.info("Adding 10 hand-written placeholder slots …")
    hand_pool = [c for c in chunks if len(c.payload.get("text", "")) > 200]
    rng.shuffle(hand_pool)
    for i in range(10):
        chunk = hand_pool[i % len(hand_pool)]
        entries.append({
            "id":                      str(uuid.uuid4()),
            "question":                "[HAND-WRITTEN]",
            "ground_truth_chunk_id":   str(chunk.id),
            "ground_truth_answer":     "",
            "_hint":                   {
                "repo":   chunk.payload.get("repo", ""),
                "file":   chunk.payload.get("source_file", ""),
                "text":   chunk.payload.get("text", "")[:300],
            },
        })

    # ------------------------------------------------------------------
    # Write dataset
    # ------------------------------------------------------------------
    rng.shuffle(entries)  # mix order
    DATASET_PATH.write_text(
        json.dumps({"entries": entries}, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    log.info(f"Wrote {len(entries)} entries to {DATASET_PATH}")
    log.info(f"  Generated : {single_done + multi_done}")
    log.info(f"  Hand-written slots: 10")


if __name__ == "__main__":
    main()
